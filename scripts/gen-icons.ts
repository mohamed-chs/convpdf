/**
 * Extract the callout icons we need from lucide-static into a small
 * generated module, so the full icon set is not a runtime dependency.
 *
 *   node scripts/gen-icons.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const dir = join(dirname(require.resolve('lucide-static/package.json')), 'icons');

const ICONS = [
  'pencil', 'info', 'lightbulb', 'message-square-warning', 'triangle-alert', 'octagon-alert',
  'clipboard-list', 'circle-check', 'flame', 'check', 'circle-help', 'x', 'zap', 'bug', 'list', 'quote',
  'link', 'file-text', 'paperclip', 'chevron-right',
];

let out = '// Generated by scripts/gen-icons.ts from lucide-static (ISC license). Do not edit.\n\n';
out += 'export const ICONS: Record<string, string> = {\n';
for (const name of ICONS) {
  const svg = readFileSync(join(dir, `${name}.svg`), 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[\s\S]*?>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/\s*\/>/g, '/>')
    .trim();
  const full =
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" ' +
    'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' + inner + '</svg>';
  out += `  '${name}': '${full}',\n`;
}
out += '};\n';
writeFileSync(new URL('../src/markdown/icons.ts', import.meta.url), out);
console.log(`wrote ${ICONS.length} icons`);
